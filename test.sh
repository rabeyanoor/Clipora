Keep your project format portable
Represent every edit as structured project data rather than permanently baking changes into the original video.

For example, save the selected source clips, trim points, caption text, audio levels, aspect ratio and style settings as a versioned project document. Then the web editor, mobile editor and rendering workers can interpret the same project.

That decision will make it much easier to support undo/redo, save drafts, change devices and add natural-language editing later.

