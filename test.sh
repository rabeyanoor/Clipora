Startup plan: AI video editor for global creators
My recommendation is to build an AI-first video editor that turns raw footage into publish-ready short videos, while keeping the result fully editable.

Do not try to rebuild every CapCut and InShot feature at the beginning. Start with one workflow that saves creators time, prove that people will pay for it, and then expand into a complete editor.


Working product concept: ClipPilot AI
A temporary name for planning, not a checked trademark or available domain.

One-line pitch: Upload a long video, get several intelligently selected short clips with captions and reframing, edit them with simple instructions, and export for social media.

